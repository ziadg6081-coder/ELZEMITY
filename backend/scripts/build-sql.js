'use strict';
/** Builds database/oriantal_perfumes_full.sql: everything needed to create the DB by pasting into MySQL Workbench / phpMyAdmin / mysql CLI.
 *  It also records the migrations in schema_migrations so `npm run migrate` later sees the schema as up to date. */
const fs = require('fs'); const path = require('path');
const { files, MIGRATIONS_DIR } = require('./lib');
const crypto = require('crypto');
const root = path.join(__dirname, '..', 'database');
let out = `-- Oriantal Perfumes - full MySQL schema (MySQL 8.0.16+)\n-- Generated by scripts/build-sql.js from database/migrations/*.sql\nCREATE DATABASE IF NOT EXISTS \`oriantal_perfumes\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\nUSE \`oriantal_perfumes\`;\n\n`;
out += `CREATE TABLE IF NOT EXISTS schema_migrations (version VARCHAR(20) NOT NULL PRIMARY KEY, name VARCHAR(190) NOT NULL, checksum CHAR(64) NOT NULL, applied_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n\n`;
for (const f of files()) {
  const sql = fs.readFileSync(path.join(MIGRATIONS_DIR, f), 'utf8');
  out += `-- ======== ${f} ========\n${sql}\n`;
  out += `INSERT INTO schema_migrations (version, name, checksum) VALUES ('${f.split('_')[0]}','${f}','${crypto.createHash('sha256').update(sql).digest('hex')}');\n\n`;
}
fs.writeFileSync(path.join(root, 'oriantal_perfumes_full.sql'), out);
console.log('written database/oriantal_perfumes_full.sql');
